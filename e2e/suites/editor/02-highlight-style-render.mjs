// The code highlighter, the Lang select, font / size / colour spans (the T popover), the rendered page, and
// the cell / seam arrow-key walk. (Was wm/features.mjs.)
import { setRendered, ok, finish, js, sleep, freshNote, setDoc, doc, setSel, key, typeText, click, shot, lineTexts, press, armed, pick, pickCodeLanguage } from "../../lib/harness.mjs"

await freshNote()
const tokens = (cls) => js(`[...document.querySelectorAll('.${cls}')].map(e=>e.textContent)`)
const V = `document.querySelector('.cm-content').cmTile.view`

// ---- the code highlighter
await setDoc("```python\ndef f(x):\n    return 'a' # hi\n```\n\n```wolfram\nSin[x_Integer] := (* c *) 2.5\n```\n\n```rust\nfn main() { let n: u32 = 1; }\n```")
await sleep(400)
const kw = await tokens("wm-tok-keyword")
ok("python keyword def is coloured", kw.includes("def"), JSON.stringify(kw))
ok("python return is coloured", kw.includes("return"))
ok("python string is coloured", (await tokens("wm-tok-string")).includes("'a'"))
ok("python comment is coloured", (await tokens("wm-tok-comment")).includes("# hi"))
ok("wolfram nested comment is a comment", (await tokens("wm-tok-comment")).includes("(* c *)"))
ok("wolfram pattern is a type", (await tokens("wm-tok-type")).includes("x_Integer"))
ok("wolfram built-in is a keyword", kw.includes("Sin"))
ok("rust fn / let are coloured", kw.includes("fn") && kw.includes("let"))
ok("rust u32 is a type", (await tokens("wm-tok-type")).includes("u32"))
ok("the note is unchanged by colouring", (await doc()).startsWith("```python\ndef f(x):"))
const colours = await js(`(()=>{const k=document.querySelector('.wm-tok-keyword');return [getComputedStyle(k).color,getComputedStyle(document.querySelector('.cm-content')).color]})()`)
ok("a keyword's colour is not the text colour", colours[0] !== colours[1], JSON.stringify(colours))
await shot("highlight")

// ---- the code-language chevron picks the language of the next fenced block
await setDoc("")
await pickCodeLanguage("rust")
await typeText("fn main() {}")
await sleep(300)
ok("the Code button's menu tags the fence it writes (and writes one)", (await doc()).startsWith("```rust\n"), JSON.stringify(await doc()))
ok("and the block is coloured", (await tokens("wm-tok-keyword")).includes("fn"))
await js(`document.querySelector('[data-bar=code]').dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,cancelable:true}))`); await sleep(150)
await js(`document.querySelector('.float-menu [data-bar="code-plain"]').click()`); await sleep(250)

// ---- font, size, colour: a <span style> around the selection (the T popover)
await setDoc("at dawn")
await js(`${V}.dispatch({selection:{anchor:3,head:7}})`)
const tButton = `document.querySelector('[data-bar=font]')`
await js(`${tButton}.click()`); await sleep(200)
await js(`(()=>{const boxes=document.querySelector('.style-pop').querySelectorAll('input[type=checkbox]');[boxes[1],boxes[2]].forEach(b=>b.click())})()`)
await sleep(100)
await js(`[...document.querySelectorAll('.style-pop button')].find(b=>b.textContent==='Apply').click()`); await sleep(300)
const styled = await doc()
// (A text cell styled becomes a markdown cell: its marker goes in above the words.)
ok("Apply writes a span with size and colour", /^<!-- markdown -->\nat <span style="font-size: 18px; color: #2D7DD2">dawn<\/span>$/.test(styled), JSON.stringify(styled))
ok("the span is drawn in its colour", (await js(`(()=>{const e=document.querySelector('.cm-line span[style]');return e?getComputedStyle(e).color:''})()`)) === "rgb(45, 125, 210)")
ok("the span's tags are faded, not shown loose", (await js(`document.querySelectorAll('.wm-marker').length`)) >= 2)
await js(`${V}.dispatch({selection:{anchor:${styled.indexOf("dawn")},head:${styled.indexOf("dawn") + 4}}})`)
await js(`${tButton}.click()`); await sleep(200)
await js(`[...document.querySelectorAll('.style-pop button')].find(b=>b.textContent==='Remove').click()`); await sleep(300)
ok("Remove takes the span off", (await doc()) === "<!-- markdown -->\nat dawn", JSON.stringify(await doc()))

// ---- the rendered page (the markdown button in the sidebar's bar)
await setDoc("# Title\n\nsome **bold** and [a link](x.md) here\n\nlast")
await setSel((await doc()).length)
const before = await lineTexts()
ok("markdown shows its marks", before[0] === "# Title" && before[2].includes("**bold**"), JSON.stringify(before))
await setRendered(true)
// the rendered page draws a cell as a block (.wm-pv) rather than as a source line, so read the whole text
const pageText = () => js(`document.querySelector('.cm-content').innerText`)
const after = await pageText()
ok("rendered: the heading shows without its hash", after.startsWith("Title") && !after.includes("# Title"), JSON.stringify(after))
ok("rendered: bold and link lose their marks", after.includes("some bold and a link here"), JSON.stringify(after))
ok("rendered: the heading is set as a heading", await js(`!!document.querySelector('.cm-content .wm-pv-heading')`))
ok("rendered: the link is a link", await js(`document.querySelector('.cm-content a.wm-pv-link')?.dataset.href === 'x.md'`))
ok("rendered: brackets and seams are still there", (await js(`document.querySelectorAll('.wm-bracket').length`)) >= 3)
ok("rendered: the note is untouched", (await doc()).startsWith("# Title\n\nsome **bold**"))
await setSel(12); await sleep(200)
ok("rendered: the caret's cell shows its source", (await pageText()).includes("some **bold** and [a link](x.md) here"), JSON.stringify(await pageText()))
await shot("rendered")
await setRendered(false)
ok("back to markdown", (await lineTexts())[0] === "# Title")
finish()
