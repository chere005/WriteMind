// The handles round a picked object and the one inspector over it (P5, docs/PLAN-bars-2026-10.md; Sean's wireframe,
// 2026-10-10: docs/ui-2026-10/FinalTablet.png): eight resize handles ON the outline and a rotate dot, one pill for a small
// object, the inspector above (below when there is no room, never over the object), delete on a click, Escape for its
// popovers, the arrow's heads row alone beside its end, a multi-selection's bar, a picture's crop.
import {
  ok, finish, js, sleep, freshNote, canvasBox, saved, arm, handles, click, drag, dragPath, line, key, mouse, hover, shot, rectOf,
  centerOf, clearDrawing,
} from "../../lib/harness.mjs"

const file = await freshNote({ rendered: true })
const cb = await canvasBox()
const X = (dx) => cb.x + dx, Y = (dy) => cb.y + dy
const items = async () => (await saved(file)).items
const shapes = async () => (await items()).filter((i) => i.kind === "shape")
const insp = () => rectOf(".wm-insp")
const spanOf = (hs) => ({ l: Math.min(...hs.map((h) => h.x)), r: Math.max(...hs.map((h) => h.x)), t: Math.min(...hs.map((h) => h.y)), b: Math.max(...hs.map((h) => h.y)) })
const ring = async () => (await handles()).filter((h) => h.t === "Resize")
const dot = async () => (await handles()).find((h) => h.t === "Turn")
const has = (what) => js(`!!document.querySelector('.wm-insp [data-insp="${what}"]')`)
const insideBar = (what) => js(`(()=>{const b=document.querySelector('.wm-insp [data-insp="${what}"]');return b?JSON.stringify((()=>{const r=b.getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height/2}})()):'null'})()`).then(JSON.parse)
const pressBar = async (what) => { const c = await insideBar(what); await click(c.x, c.y); await sleep(250) }
const popOpen = () => js(`!!document.querySelector('.wm-insp-pop')`)

// ---- a rectangle: eight handles on its outline, a rotate dot above, the bar over that
await arm("rectangle"); await drag(X(300), Y(330), X(540), Y(450)); await sleep(300)
let rs = await ring()
ok("a picked rectangle has eight resize handles", rs.length === 8, JSON.stringify(rs.map((h) => h.h)))
ok("...named for the corners and edges", ["nw", "n", "ne", "e", "se", "s", "sw", "w"].every((id) => rs.some((h) => h.h === id)))
const dt = await dot()
ok("...and one rotate dot", !!dt && dt.h === "rotate")
let sp = spanOf(rs)
ok("the ring stands ON the object's outline (a 240 x 120 rectangle, 3 px out)", Math.abs((sp.r - sp.l) - 246) < 4 && Math.abs((sp.b - sp.t) - 126) < 4, JSON.stringify(sp))
const mid = (id) => rs.find((h) => h.h === id)
ok("the edge handles are in the middle of their edges", Math.abs(mid("n").x - (sp.l + sp.r) / 2) < 2 && Math.abs(mid("e").y - (sp.t + sp.b) / 2) < 2)
ok("the rotate dot is above the top edge", dt.y < sp.t - 15 && Math.abs(dt.x - (sp.l + sp.r) / 2) < 2, JSON.stringify([dt, sp]))
ok("no handle stands in the middle of the object (the words' place)", rs.every((h) => !(h.x > sp.l + 10 && h.x < sp.r - 10 && h.y > sp.t + 10 && h.y < sp.b - 10)))
let bar = await insp()
ok("the inspector is over the object, on the pane", !!bar && bar.y + bar.h < dt.y - 4, JSON.stringify([bar, dt]))
ok("...and not over it", bar && (bar.b <= sp.t || bar.y >= sp.b))
ok("it names the object", (await js(`document.querySelector('[data-insp=name]')?.textContent`)) === "Rectangle")
ok("a rectangle's bar: colour, width, fill, Aa, order, dock, copy, delete",
  (await Promise.all(["colour", "width", "fill", "label", "order", "dock", "duplicate", "delete"].map(has))).every(Boolean))
ok("none of the six old glyph discs is there", !(await js(`!!document.querySelector('[data-handle=style], [data-handle=move], [data-group=group], .wm-handle-group')`)))
ok("a bar button is a 28 px target", (await js(`document.querySelector('.wm-insp [data-insp=colour]').getBoundingClientRect().height`)) >= 28)
await shot("rectangle")

// ---- a corner scales about the OPPOSITE corner; an edge STRETCHES a node
const nw0 = mid("nw"), se0 = mid("se")
await drag(se0.x, se0.y, se0.x + 60, se0.y + 30, { steps: 8 }); await sleep(300)
rs = await ring(); sp = spanOf(rs)
ok("dragging the south-east corner keeps the north-west corner where it was", Math.abs(mid("nw").x - nw0.x) < 2 && Math.abs(mid("nw").y - nw0.y) < 2, JSON.stringify([nw0, mid("nw")]))
ok("...and the box got bigger", (sp.r - sp.l) > 246 + 20, JSON.stringify(sp))
const before = spanOf(rs)
const east = rs.find((h) => h.h === "e")
await drag(east.x, east.y, east.x + 100, east.y + 40, { steps: 8 }); await sleep(300)
rs = await ring(); sp = spanOf(rs)
ok("dragging the east edge widens it by what the pointer went", Math.abs((sp.r - before.r) - 100) < 4, JSON.stringify([before, sp]))
ok("...the west edge, and the height, did not move (a stretch, not a scale)", Math.abs(sp.l - before.l) < 2 && Math.abs(sp.t - before.t) < 2 && Math.abs(sp.b - before.b) < 2)
const south = rs.find((h) => h.h === "s")
await drag(south.x, south.y, south.x + 20, south.y + 50, { steps: 8 }); await sleep(300)
rs = await ring(); const sp2 = spanOf(rs)
ok("the south edge deepens it and holds the top", Math.abs((sp2.b - sp.b) - 50) < 4 && Math.abs(sp2.t - sp.t) < 2 && Math.abs(sp2.r - sp.r) < 2, JSON.stringify([sp, sp2]))
const turnFrom = await dot()
await dragPath(line([turnFrom.x, turnFrom.y], [turnFrom.x + 150, turnFrom.y + 150], 12)); await sleep(300)
const turned = (await shapes())[0]
ok("the rotate dot turns it", Math.abs(turned.transform.rotation) > 0.3, JSON.stringify(turned.transform))
ok("a turned node no longer stretches: its edges scale (all eight handles are still there)", (await ring()).length === 8)
await key("z", { modifiers: 2 }); await sleep(250)
await key("z", { modifiers: 2 }); await sleep(250)
await key("z", { modifiers: 2 }); await sleep(250)
await key("z", { modifiers: 2 }); await sleep(250)
ok("each of the four gestures was ONE Ctrl+Z", (await shapes()).length === 1 && Math.abs((await shapes())[0].transform.rotation) < 1e-9 && (await shapes())[0].transform.scale === 1,
  JSON.stringify((await shapes())[0]?.transform))
await shot("resized")

// ---- the order, colour, width, fill popovers; Escape closes ONLY the popover
await pressBar("colour")
ok("the colour button opens its popover", await popOpen())
ok("...with six swatches and a colour well", (await js(`document.querySelectorAll('.wm-insp-pop .wm-swatch').length`)) === 6 && (await js(`!!document.querySelector('.wm-insp-pop input[type=color]')`)))
await key("Escape"); await sleep(200)
ok("Escape closes the popover", !(await popOpen()))
ok("...and only it: the object is still picked", (await ring()).length === 8)
await pressBar("colour")
await js(`document.querySelector('.wm-insp-pop [data-colour="#F2542D"]').click()`); await sleep(300)
ok("a swatch colours the rectangle and closes the popover", (await shapes())[0].colorHex.toLowerCase() === "#f2542d" && !(await popOpen()))
await pressBar("width")
ok("the width popover offers the pen's six widths", (await js(`[...document.querySelectorAll('.wm-insp-pop [data-width]')].map(b=>b.dataset.width).join(',')`)) === "1,2,3,5,8,12")
await js(`document.querySelector('.wm-insp-pop [data-width="8"]').click()`); await sleep(300)
ok("a width sets the outline", (await shapes())[0].lineWidth === 8)
ok("the bar shows it", (await js(`document.querySelector('.wm-insp [data-insp=width] .wm-insp-value').textContent`)) === "8")
await pressBar("fill")
await js(`document.querySelector('.wm-insp-pop [data-fill="#FFFFFF"]').click()`); await sleep(300)
ok("a fill fills it", (await shapes())[0].fillHex?.toLowerCase() === "#ffffff")
await pressBar("order")
ok("the order popover has four rows", (await js(`document.querySelectorAll('.wm-insp-pop [data-style]').length`)) === 4)
await pressBar("order")   // the same button closes it
ok("the same button closes it again", !(await popOpen()))
await pressBar("colour")
await click(X(900), Y(700)); await sleep(250)
ok("a press anywhere else closes a popover (and puts the pick away, as it always did)", !(await popOpen()))

// ---- the label: Aa, and no delete while it is being typed
await click(X(420), Y(390)); await sleep(500)
await pressBar("label")
ok("Aa opens the label field", await js(`!!document.querySelector('.wm-label-edit')`))
ok("...and the delete button is hidden while it is edited (the copy stays)", !(await has("delete")) && (await has("duplicate")))
await js(`document.querySelector('.wm-label-edit').value`)
await key("Escape"); await sleep(250)
ok("Escape ends it and the delete is back", !(await js(`!!document.querySelector('.wm-label-edit')`)) && (await has("delete")))

// ---- delete fires on a click: pressed on it and let go elsewhere does nothing; pressed and let go on it deletes
const del = await insideBar("delete")
ok("the delete reads red", (await js(`getComputedStyle(document.querySelector('.wm-insp [data-insp=delete]')).color`)) === "rgb(192, 57, 43)")
await hover(del.x, del.y)
await mouse("mousePressed", del.x, del.y)
await mouse("mouseMoved", del.x + 200, del.y + 200)
await mouse("mouseReleased", del.x + 200, del.y + 200)
await sleep(400)
ok("a press that was let go off the button deletes nothing", (await shapes()).length === 1)
await click(X(420), Y(390)); await sleep(500)
const del2 = await insideBar("delete")
if (del2) await click(del2.x, del2.y)
await sleep(500)
ok("a press and a lift on it deletes", (await shapes()).length === 0 && (await handles()).length === 0 && !(await insp()))

// ---- no room above: the bar goes under the object; and it never lies on it
await arm("rectangle"); await drag(X(300), Y(6), X(500), Y(60)); await sleep(350)
bar = await insp(); rs = await ring(); sp = spanOf(rs)
ok("an object at the top of the pane has its bar below it", bar && bar.y >= sp.b, JSON.stringify([bar, sp]))
ok("...kept on the pane", bar && bar.y + bar.h <= cb.y + cb.h && bar.x >= cb.x)
await shot("bar-below")
await clearDrawing()

// ---- a small object: ONE PILL, not a ring
await arm("rectangle"); await drag(X(400), Y(300), X(430), Y(325)); await sleep(350)
let hs = await handles()
ok("a small object has two buttons in one pill, not nine handles", hs.length === 2 && hs.some((h) => h.h === "pill-turn") && hs.some((h) => h.h === "pill-resize"), JSON.stringify(hs.map((h) => h.h)))
ok("...under it", hs.every((h) => h.y > Y(325)))
const pill = hs.find((h) => h.h === "pill-resize")
const sizeBefore = (await shapes())[0]
await drag(pill.x, pill.y, pill.x + 40, pill.y + 40, { steps: 6 }); await sleep(300)
ok("the pill's resize scales it", (await shapes())[0].transform.scale > 1.3, JSON.stringify((await shapes())[0].transform))
await clearDrawing()

// ---- an arrow: the arrow tool opens the heads row alone, beside the arrow's end
await arm("rectangle"); await drag(X(300), Y(250), X(440), Y(320)); await sleep(200)
await arm("rectangle"); await drag(X(640), Y(430), X(780), Y(500)); await sleep(200)
await arm("tool"); await drag(X(370), Y(285), X(710), Y(465), { steps: 12 }); await sleep(400)
await arm("tool")
bar = await insp()
ok("after the arrow tool the bar is the heads row alone", !!bar && (await has("heads")) && !(await has("delete")) && !(await has("colour")) && !(await js(`!!document.querySelector('[data-insp=name]')`)))
ok("...it is not over the nodes", bar && !(bar.x < X(780) && bar.x + bar.w > X(640) && bar.y < Y(500) && bar.y + bar.h > Y(430)) && !(bar.x < X(440) && bar.x + bar.w > X(300) && bar.y < Y(320) && bar.y + bar.h > Y(250)), JSON.stringify(bar))
ok("...and near the arrow's end", bar && Math.hypot(Math.max(bar.x, Math.min(X(710), bar.x + bar.w)) - X(710), Math.max(bar.y, Math.min(Y(465), bar.y + bar.h)) - Y(465)) < 90, JSON.stringify(bar))
ok("an arrow has no turn or resize handle", (await handles()).filter((h) => h.t === "Turn" || h.t === "Resize").length === 0)
await shot("arrow-compact")
await key("Escape"); await sleep(250)
ok("Escape puts the compact bar, and the pick, away", !(await insp()) && (await handles()).length === 0)
// a click on the arrow and the whole bar (an arrow's has the heads too)
const conn = (await items()).find((i) => i.kind === "connector")
await click(X(710), Y(380)); await sleep(500)
ok("picked again, the arrow has the whole bar: colour, width, heads, order, copy, delete", (await Promise.all(["colour", "width", "heads", "order", "duplicate", "delete"].map(has))).every(Boolean))
await pressBar("heads").catch(() => {})
await js(`document.querySelector('[data-style="startHead:arrow"]').click()`); await sleep(300)
ok("a head button puts a head at the start", (await items()).find((i) => i.kind === "connector")?.startHead === "arrow")
await js(`document.querySelector('[data-style="line:dashed"]').click()`); await sleep(300)
ok("a line button dashes it", (await items()).find((i) => i.kind === "connector")?.line === "dashed")
void conn

// ---- several objects: Group, order, copy, delete
await clearDrawing()
await arm("rectangle"); await drag(X(300), Y(300), X(440), Y(380)); await sleep(200)
await arm("oval"); await drag(X(560), Y(320), X(700), Y(400)); await sleep(200)
await click(X(900), Y(700)); await sleep(150)
await dragPath(line([X(260), Y(260)], [X(740), Y(440)], 14), { modifiers: 2 }); await sleep(350)
ok("a marquee over two nodes: one bar named for them", (await js(`document.querySelector('[data-insp=name]')?.textContent`)) === "2 objects")
ok("...Group, order, copy and delete, no colour or width", (await Promise.all(["group", "order", "duplicate", "delete"].map(has))).every(Boolean) && !(await has("colour")) && !(await has("width")))
ok("...and the ring round both", (await ring()).length === 8)
await shot("multi")
await pressBar("group")
ok("Group holds them together (the button says Ungroup now)", (await js(`document.querySelector('[data-insp=group]')?.dataset.group`)) === "ungroup" && new Set((await shapes()).map((s) => s.group)).size === 1)
await pressBar("duplicate")
ok("copy makes two more, picked", (await shapes()).length === 4)
await pressBar("delete")
ok("delete takes the picked pair", (await shapes()).length === 2 && !(await insp()))
await clearDrawing()

// ---- a picture: crop and Aa live in the bar; the crop box takes over the handles; delete is hidden while it is open
await js(`(async()=>{const c=document.createElement('canvas');c.width=320;c.height=200;const x=c.getContext('2d');const g=x.createLinearGradient(0,0,320,200);g.addColorStop(0,'#f2542d');g.addColorStop(1,'#2d7dd2');x.fillStyle=g;x.fillRect(0,0,320,200);const blob=await new Promise(r=>c.toBlob(r,'image/png'));const dt=new DataTransfer();dt.items.add(new File([blob],'p.png',{type:'image/png'}));document.dispatchEvent(new ClipboardEvent('paste',{clipboardData:dt,bubbles:true,cancelable:true}))})()`)
await sleep(1300)
ok("a pasted picture arrives picked, named Picture, with crop in its bar", (await js(`document.querySelector('[data-insp=name]')?.textContent`)) === "Picture" && (await has("crop")))
ok("...with the full ring", (await ring()).length === 8)
await shot("picture")
await pressBar("crop")
ok("crop opens its box", await js(`!!document.querySelector('.wm-crop')`))
ok("...the ring gives way to the crop's own corners", (await ring()).length === 0 && (await js(`document.querySelectorAll('.wm-crop-corner').length`)) === 4)
ok("...and the delete is hidden while it is open", !(await has("delete")) && (await has("duplicate")))
const okB = await centerOf(".wm-crop-ok"), barNow = await insp()
ok("...and the bar does not lie over the crop's buttons", barNow && !(okB.x > barNow.x && okB.x < barNow.r && okB.y > barNow.y && okB.y < barNow.b), JSON.stringify([okB, barNow]))
await shot("crop")
await key("Escape"); await sleep(250)
ok("Escape closes the crop box and the delete is back", !(await js(`!!document.querySelector('.wm-crop')`)) && (await has("delete")))

// ---- the bar never takes the keyboard from the note
await clearDrawing()
await arm("rectangle"); await drag(X(300), Y(300), X(440), Y(380)); await sleep(300)
await js(`document.querySelector('.cm-content').focus()`)
await pressBar("colour"); await key("Escape")
ok("after a popover the keyboard is still the note's", await js(`document.activeElement === document.querySelector('.cm-content')`))
finish()
